#!/usr/bin/env python3
"""
Apply rank/name field corrections during ETL processing

This script implements the correction processor that applies the mappings
generated by generate_corrections.py during the ETL pipeline.
"""

import json
import logging
from pathlib import Path
from typing import Dict, Tuple

from etl.transform import debug_files, private_rules

# Paths
DOMAIN_PATH = Path(__file__).parent.parent
CORRECTIONS_PATH = DOMAIN_PATH / "corrections"
CORRECTION_LOG_FILE = CORRECTIONS_PATH / "applied_corrections.log"


class RankNameCorrector:
    """Apply rank/name field corrections to police officer data"""

    def __init__(self):
        self.corrections = {}
        self.applied_corrections = []
        self.logger = logging.getLogger(__name__)
        self._load_corrections()

    def _load_corrections(self):
        """Load the row-specific corrections; they name officers, so they are
        private rules rather than a file in this package."""
        data = private_rules.load(private_rules.OFFICER_CORRECTIONS)
        if data is None:
            self.logger.warning(
                f"Officer corrections not found: {private_rules.OFFICER_CORRECTIONS}"
            )
            return

        try:
            # Index corrections by row_id and officer_type for fast lookup
            for correction in data.get("corrections", []):
                if correction.get("ready", False):  # Only apply ready corrections
                    key = f"{correction['row_id']}_{correction['officer_type']}"
                    self.corrections[key] = correction

            self.logger.info(f"Loaded {len(self.corrections)} ready corrections")

        except Exception as e:
            self.logger.error(f"Error loading corrections: {e}")

    def apply_corrections(
        self, row_id: int, officer_data: Dict, officer_type: str
    ) -> Tuple[Dict, bool]:
        """
        Apply corrections to officer data if applicable

        Args:
            row_id: Row identifier
            officer_data: Officer data dict with name, rank, badge_id
            officer_type: 'submitting_officer' or 'requesting_officer'

        Returns:
            Tuple of (corrected_officer_data, was_corrected)
        """
        key = f"{row_id}_{officer_type}"

        if key not in self.corrections:
            return officer_data, False

        correction = self.corrections[key]

        # Verify the correction still applies (data might have changed)
        if (
            officer_data.get("name") == correction["original_name"]
            and officer_data.get("rank") == correction["original_rank"]
        ):

            # Apply the correction
            corrected_data = officer_data.copy()
            corrected_data["name"] = correction["corrected_name"]
            corrected_data["rank"] = correction["corrected_rank"]

            # Log the applied correction
            self._log_applied_correction(
                row_id, officer_type, correction, officer_data, corrected_data
            )

            return corrected_data, True

        return officer_data, False

    def _log_applied_correction(
        self,
        row_id: int,
        officer_type: str,
        correction: Dict,
        original_data: Dict,
        corrected_data: Dict,
    ):
        """Log applied correction for audit trail"""
        log_entry = {
            "timestamp": "2025-09-25T12:35:00",
            "row_id": row_id,
            "officer_type": officer_type,
            "pattern": correction["pattern"],
            "confidence": correction["confidence"],
            "original": {
                "name": original_data.get("name", ""),
                "rank": original_data.get("rank", ""),
                "badge_id": original_data.get("badge_id", ""),
            },
            "corrected": {
                "name": corrected_data.get("name", ""),
                "rank": corrected_data.get("rank", ""),
                "badge_id": corrected_data.get("badge_id", ""),
            },
        }

        self.applied_corrections.append(log_entry)

        # Also log to file, when diagnostic files are on (never in the app)
        if not debug_files.enabled():
            return
        try:
            with open(CORRECTION_LOG_FILE, "a") as f:
                f.write(f"{json.dumps(log_entry)}\n")
        except Exception as e:
            self.logger.error(f"Error writing correction log: {e}")

    def get_correction_stats(self) -> Dict:
        """Get statistics about applied corrections"""
        pattern_counts = {}
        for correction in self.applied_corrections:
            pattern = correction["pattern"]
            pattern_counts[pattern] = pattern_counts.get(pattern, 0) + 1

        return {
            "total_applied": len(self.applied_corrections),
            "patterns": pattern_counts,
            "available_corrections": len(self.corrections),
        }


def apply_rank_name_corrections(
    row_id: int, police_officer_data: Dict
) -> Tuple[Dict, Dict]:
    """
    Main function to apply rank/name corrections to police officer data

    Args:
        row_id: Row identifier
        police_officer_data: Full police officer data structure

    Returns:
        Tuple of (corrected_police_officer_data, correction_stats)
    """
    corrector = RankNameCorrector()
    corrected_data = police_officer_data.copy()
    corrections_applied = []

    # Apply corrections to submitting officer
    if "submitting_officer" in corrected_data:
        corrected_submitting, was_corrected = corrector.apply_corrections(
            row_id, corrected_data["submitting_officer"], "submitting_officer"
        )
        corrected_data["submitting_officer"] = corrected_submitting
        if was_corrected:
            corrections_applied.append("submitting_officer")

    # Apply corrections to requesting officer
    if "requesting_officer" in corrected_data:
        corrected_requesting, was_corrected = corrector.apply_corrections(
            row_id, corrected_data["requesting_officer"], "requesting_officer"
        )
        corrected_data["requesting_officer"] = corrected_requesting
        if was_corrected:
            corrections_applied.append("requesting_officer")

    correction_stats = {
        "corrections_applied": corrections_applied,
        "total_corrections": len(corrections_applied),
    }

    return corrected_data, correction_stats


def main():
    """Test the correction system"""
    print("Testing rank/name correction system...")

    # Test with the known problematic case (row 46)
    test_data = {
        "submitting_officer": {
            "name": "Ursula",
            "rank": "Senior Constable",
            "badge_id": "PD7895",
        },
        "requesting_officer": {"name": "PC", "rank": "Belmore", "badge_id": ""},
        "organisation": "Rockingham Divisional Support Group",
    }

    print(f"Original data: {json.dumps(test_data, indent=2)}")

    corrected_data, stats = apply_rank_name_corrections(46, test_data)

    print(f"\nCorrected data: {json.dumps(corrected_data, indent=2)}")
    print(f"\nCorrection stats: {json.dumps(stats, indent=2)}")

    # Test correction system stats
    corrector = RankNameCorrector()
    system_stats = corrector.get_correction_stats()
    print(f"\nSystem stats: {json.dumps(system_stats, indent=2)}")


if __name__ == "__main__":
    main()
